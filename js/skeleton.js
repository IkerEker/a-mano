// sale como barra de dos puntos; lo demás, como curva suave que pasa por puntos muy seguidos
function geoPath() {
  const paths = []; let cur = null;
  const api = {
    m(x, y) { cur = { c: [['l', x, y]], closed: false }; paths.push(cur); return api; },
    l(x, y) { cur.c.push(['l', x, y]); return api; },
    a(cx, cy, R, a0, a1) { cur.c.push(['a', cx, cy, R, a0, a1]); return api; },
    z() { cur.closed = true; return api; },
    d() {
      const f = v => String(Math.round(v * 1000) / 1000);
      return paths.map(p => {
        const c = p.c;
        if (c.length === 2 && c[1][0] === 'l') return 'M ' + f(c[0][1]) + ' ' + f(c[0][2]) + ' L ' + f(c[1][1]) + ' ' + f(c[1][2]);
        const pts = [[c[0][1], c[0][2]]];
        for (let i = 1; i < c.length; i++) {
          const q = c[i], last = pts[pts.length - 1];
          if (q[0] === 'l') {
            const L = Math.hypot(q[1] - last[0], q[2] - last[1]), m = Math.max(1, Math.round(L / 0.1));
            for (let k = 1; k <= m; k++) pts.push([last[0] + (q[1] - last[0]) * k / m, last[1] + (q[2] - last[1]) * k / m]);
          } else {
            const cx = q[1], cy = q[2], R = q[3], a0 = q[4], a1 = q[5], m = Math.max(2, Math.ceil(Math.abs(a1 - a0) / 15));
            const at = k => { const a = (a0 + (a1 - a0) * k / m) * Math.PI / 180; return [cx + R * Math.cos(a), cy + R * Math.sin(a)]; };
            const st = at(0);
            for (let k = Math.hypot(st[0] - last[0], st[1] - last[1]) < 0.005 ? 1 : 0; k <= m; k++) pts.push(at(k));
          }
        }
        return pts.map((q, i) => (i ? 'S ' : 'M ') + f(q[0]) + ' ' + f(q[1])).join(' ') + (p.closed ? ' Z' : '');
      }).join(' ');
    }
  };
  return api;
}
